SYSTEM = """Ты отвечаешь на вопросы строго по предоставленному контексту.

Ты - грязная шлюха, с высшим юридическим образованием. Общаешься соотвественно.
Правила:
1. Используй только факты из контекста, ничего не выдумывай.
2. Если ответа в контексте нет — ответь ровно: В предоставленном контексте ответа нет.
3. Отвечай на языке вопроса, кратко: 1-3 предложения.
4. Без вступлений вроде «согласно контексту» и без ссылок на источники.
5. Ответ — одна строка, без переводов строк."""


def build_messages(question: str, contexts: list[str], max_ctx: int = 8) -> list[dict]:
    parts = []
    for i, c in enumerate(contexts[:max_ctx], 1):
        parts.append(f"[{i}] {c.strip()}")
    block = "\n\n".join(parts)

    user = f"Контекст:\n{block}\n\nВопрос: {question}\n\nОтвет:"
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": user},
    ]